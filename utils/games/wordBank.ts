/** 本地敏感词表（命中即弃用，防 AI 出题/热词出怪词） */
const SENSITIVE_PATTERNS: string[] = [
    '死', '杀', '枪', '毒', '赌', '色', '黄', '淫', '邪', '鬼', '魔',
    '总统', '主席', '总理', '官员', '党', '军', '枪械', '炸弹', '恐怖',
];

/** 敏感词过滤：命中任一返回 true */
export function isSensitiveWord(word: string): boolean {
    const w = word.trim().toLowerCase();
    if (!w) return true;
    if (w.length > 6) return true; // 出题太长弃用
    return SENSITIVE_PATTERNS.some((p) => w.includes(p));
}

/** 从某分类取一个随机词（跳过敏感词） */
export function pickWordFromCategory(category: WordCategory, used: Set<string>): string | null {
    const pool = WORD_BANK[category];
    const candidates = pool.filter((w) => !used.has(w) && !isSensitiveWord(w));
    if (candidates.length === 0) return null;
    return candidates[Math.floor(Math.random() * candidates.length)];
}

/**
 * 从已选分类里随机取一个词（优先未用过的）。
 * @param categories 启用的分类
 * @param used 本局已用词（避免重复）
 */
export function pickWord(categories: WordCategory[], used: Set<string>): string {
    // 打乱分类顺序，优先从词多的分类取
    const shuffled = [...categories].sort(() => Math.random() - 0.5);
    for (const cat of shuffled) {
        const w = pickWordFromCategory(cat, used);
        if (w) return w;
    }
    // 全用完了：忽略 used 兜底
    for (const cat of categories) {
        const pool = WORD_BANK[cat].filter((x) => !isSensitiveWord(x));
        if (pool.length) return pool[Math.floor(Math.random() * pool.length)];
    }
    // 最后的兜底
    return '大象';
}
